@Composable
internal fun EmptyLogsState(
    hasAnyLogs: Boolean,
    onRefresh: () -> Unit
) {
    val colors = PencilTheme.colors

    Column(
        modifier = Modifier
            .fillMaxWidth()
            .padding(top = 36.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Icon(
            imageVector = Icons.Default.BugReport,
            contentDescription = null,
            tint = colors.textTertiary,
            modifier = Modifier.size(46.dp)
        )
        Spacer(modifier = Modifier.height(12.dp))
        Text(
            text = if (hasAnyLogs) "No matching logs" else "No logs captured yet",
            color = colors.textSecondary,
            fontSize = 15.sp,
            fontWeight = FontWeight.Bold
        )
        Spacer(modifier = Modifier.height(4.dp))
        Text(
            text = if (hasAnyLogs) {
                "Try a different filter or search term."
            } else {
                "Crashes, errors and warnings will appear here automatically."
            },
            color = colors.textTertiary,
            fontSize = 12.sp
        )
        Spacer(modifier = Modifier.height(12.dp))
        TextButton(onClick = onRefresh) {
            Text("Refresh", color = colors.accentCyan, fontWeight = FontWeight.Bold)
        }
    }
}

